// คำนำหน้าหน่วยการปกครองที่ต้องตัดทิ้ง เรียงยาว→สั้น เพื่อให้ตัดคำยาวก่อนเสมอ
// (ไม่งั้น "องค์การบริหารส่วนตำบลบางบ่อ" จะโดน "ตำบล" กินก่อนแล้วเหลือขยะ)
const ADMIN_PREFIXES = [
  "องค์การบริหารส่วนตำบล", "องค์การบริหารส่วนจังหวัด", "เทศบาลตำบล", "เทศบาลเมือง",
  "เทศบาลนคร", "จังหวัด", "อำเภอ", "ตำบล", "แขวง", "เขต", "อบต.", "ทต.",
  "จ.", "อ.", "ต.",
];

/** ตัดคำนำหน้าหน่วยการปกครองออกจากชื่อ ("อำเภอลำลูกกา" → "ลำลูกกา") */
export function stripAdminPrefix(name: string): string {
  let s = name.trim();
  for (const p of ADMIN_PREFIXES) {
    if (s.startsWith(p) && s.length > p.length) { s = s.slice(p.length).trim(); break; }
  }
  return s;
}

/**
 * จับชื่อจังหวัดให้ตรงกับลิสต์ canonical — รับได้ทั้ง "จ.ปทุมธานี", "จังหวัดปทุมธานี",
 * "ปทุมธานี" และชื่อเล่นของกรุงเทพฯ (กทม / กทม. / กรุงเทพ / กรุงเทพฯ / บางกอก)
 * คืน null ถ้าไม่ใช่ชื่อจังหวัดที่รู้จัก
 */
export function normalizeProvince(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const s = stripAdminPrefix(String(raw)).replace(/\s+/g, "");
  if (!s) return null;
  if (/^(กทม\.?|กรุงเทพฯ?|กรุงเทพมหานคร|บางกอก)$/.test(s)) return "กรุงเทพมหานคร";
  return THAI_PROVINCES.find(p => p === s) ?? null;
}

// ที่อยู่ที่ไม่มีข้อมูลพื้นที่เลย — บ้านเลขที่ล้วน ("87/74"), ขีด, ช่องว่าง
const JUNK_ONLY = /^[-–—\s.]*$/;
const HOUSE_NUMBER_ONLY = /^[\d/\s-]+$/;

const THAI_LETTER = /[฀-๿]/;

// ภาษาไทยไม่เว้นวรรคระหว่างคำ จะเช็คว่า "คำนี้ยืนเดี่ยว" ได้ก็แค่ดูว่ามีตัวอักษรไทย
// ประกบหัวท้ายอยู่หรือเปล่า ใช้กับชื่อสั้น ๆ ที่หลุดไปโผล่กลางคำอื่นได้ง่าย
function standsAlone(text: string, term: string, at: number): boolean {
  const before = at > 0 ? text[at - 1] : "";
  const after = at + term.length < text.length ? text[at + term.length] : "";
  return !THAI_LETTER.test(before) && !THAI_LETTER.test(after);
}

/** ช่วงตัวอักษรสองช่วงนี้ทับกันไหม — ใช้กันชื่อเขตที่ซ่อนอยู่ในชื่อจังหวัด */
function overlaps(aAt: number, aLen: number, bAt: number, bLen: number): boolean {
  if (aAt < 0 || bAt < 0) return false;
  return aAt < bAt + bLen && bAt < aAt + aLen;
}

/**
 * แยก { district, province } จากข้อความที่อยู่แบบอิสระ
 *
 * คืน null ทั้งคู่เมื่อหาไม่เจอ — ตั้งใจให้ "ไม่รู้" ดีกว่า "เดาผิด" เพราะคอลัมน์นี้
 * จะถูกเอาไปใช้กรองและจัดกลุ่มต่อ
 */
export function parseThaiLocation(raw: string | null | undefined): { district: string | null; province: string | null } {
  const empty = { district: null, province: null };
  if (!raw) return empty;

  // ตัดหมายเหตุในวงเล็บ ("ปทุมธานี (ลูกค้าบูธออมสิน)") และรหัสไปรษณีย์ท้ายบรรทัด
  const text = String(raw)
    .replace(/\([^)]*\)/g, " ")
    .replace(/\b\d{5}\b/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (!text || JUNK_ONLY.test(text) || HOUSE_NUMBER_ONLY.test(text)) return empty;

  // ── จังหวัด ──
  let province: string | null = null;
  let provinceAt = -1;

  // 1) ระบุชัดด้วยคำนำหน้า — แม่นที่สุด เอาก่อน
  const explicit = text.match(/(?:จังหวัด|จ\.)\s*([฀-๿]+)/);
  if (explicit) {
    province = normalizeProvince(explicit[1]);
    if (province) provinceAt = explicit.index ?? -1;
  }
  // 2) ไล่หาชื่อจังหวัดที่โผล่ในข้อความ เลือกชื่อ "ยาวที่สุด" ที่แมตช์ เพื่อกัน
  //    เคสชื่อซ้อนกัน เช่น "นครศรีธรรมราช" ต้องไม่ถูก "นครสวรรค์" แย่งไปก่อน
  if (!province) {
    for (const p of THAI_PROVINCES) {
      const at = text.indexOf(p);
      if (at < 0) continue;
      // ชื่อจังหวัดสั้น ๆ (ตาก, เลย, น่าน, แพร่, ตรัง) ไปโผล่กลางคำอื่นได้ง่าย —
      // "ถนนตากสิน" ต้องไม่กลายเป็นจังหวัดตาก จึงบังคับให้ยืนเดี่ยว ส่วนชื่อยาว
      // ปล่อยผ่านเพราะที่อยู่ไทยเขียนติดกันได้ ("...เขตลาดกระบังกรุงเทพมหานคร")
      if (p.length <= 4 && !standsAlone(text, p, at)) continue;
      if (province === null || p.length > province.length) { province = p; provinceAt = at; }
    }
  }
  // 3) ชื่อเล่นกรุงเทพฯ
  if (!province) {
    const bkk = text.match(/กทม\.?|กรุงเทพฯ?|บางกอก/);
    if (bkk) { province = "กรุงเทพมหานคร"; provinceAt = bkk.index ?? -1; }
  }

  // ── เขต/อำเภอ ──
  let district: string | null = null;

  // 1) ระบุชัดด้วยคำนำหน้า เขต/อำเภอ/อ./อบต./เทศบาล (ไม่เอา แขวง/ตำบล เพราะเป็นหน่วยย่อยกว่า)
  const explicitD = text.match(/(?:องค์การบริหารส่วนตำบล|เทศบาล(?:ตำบล|เมือง|นคร)|อบต\.|อำเภอ|เขต|อ\.)\s*([฀-๿]+)/);
  if (explicitD) district = stripAdminPrefix(explicitD[1]) || null;

  // 2) ชื่อเขตกรุงเทพฯ ที่พิมพ์มาลอย ๆ ("ประเวศ กทม", "คลองสามวา")
  if (!district) {
    // เรียงยาว→สั้น ให้ชื่อที่เจาะจงกว่าชนะก่อน
    for (const d of [...BANGKOK_DISTRICTS].sort((a, b) => b.length - a.length)) {
      const at = text.indexOf(d);
      if (at < 0) continue;
      // "พระนคร" ซ่อนอยู่ใน "พระนครศรีอยุธยา" — ถ้าทับช่วงที่จับเป็นจังหวัดไปแล้ว
      // แปลว่าเป็นแค่ส่วนหนึ่งของชื่อจังหวัด ไม่ใช่ชื่อเขต
      if (overlaps(at, d.length, provinceAt, province?.length ?? 0)) continue;
      district = d;
      province = province ?? "กรุงเทพมหานคร";
      break;
    }
  }

  // 3) ชื่ออำเภอในพื้นที่ให้บริการ ("ลำลูกกา คลอง 4", "บางบัวทอง นนทบุรี")
  if (!district) {
    // เรียงยาว→สั้นกัน "เมืองนนทบุรี" โดน "นนทบุรี" (ซึ่งเป็นจังหวัด) บังก่อน
    const names = Object.keys(SERVICE_AREA_DISTRICTS).sort((a, b) => b.length - a.length);
    for (const d of names) {
      const at = text.indexOf(d);
      if (at < 0) continue;
      // ต้องไม่ทับกับช่วงที่จับจังหวัดไปแล้ว — "นนทบุรี" เดี่ยว ๆ คือจังหวัด ไม่ใช่อำเภอ
      if (overlaps(at, d.length, provinceAt, province?.length ?? 0)) continue;
      district = d;
      province = province ?? SERVICE_AREA_DISTRICTS[d];
      break;
    }
  }

  // 4) คำที่อยู่ "ก่อน" ชื่อจังหวัด และไม่ใช่ตัวเลข — รูปแบบ "<อำเภอ> <จังหวัด>"
  //    ที่เซลส์พิมพ์กันบ่อย เช่น "ปากเกร็ด นนทบุรี" กรณีนี้จังหวัดต้องไม่ได้อยู่ต้นข้อความ
  //    ("ปทุมธานี คลอง 4" = จังหวัดมาก่อน ส่วนที่ตามมาไม่ใช่อำเภอ)
  if (!district && province && provinceAt > 0) {
    const before = text.slice(0, provinceAt).trim().split(" ").pop() ?? "";
    const cand = stripAdminPrefix(before);
    if (cand && /^[฀-๿]{3,}$/.test(cand) && !normalizeProvince(cand)) district = cand;
  }

  return { district: district || null, province };
}
