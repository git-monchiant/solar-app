-- ตัด 2 ข้อออกจากขอบเขตงานของ Package O&M (ผู้ใช้สั่ง 2 ต.ค. 69 · แผน docs/plan/20261002-06-om-package-scope-trim.md)
--
-- ขอบเขตงาน (om_packages.scope) = รายละเอียดตั้งต้นใต้แพ็กเกจในใบเสนอราคา + หัวข้อ "ขอบเขตงาน" ท้ายใบ
--   เดิม (seed ใน 20260924-1400_om_packages.sql):
--     รายครั้ง  ล้างแผง+ตรวจสอบระบบ+ออกใบงานแจ้งผลการดำเนินงาน
--     สัญญา    ล้างแผง+ตรวจสอบระบบ+ออกใบงานแจ้งผลการดำเนินงาน+ตรวจเช็คตามการแจ้งซ่อมระหว่างสัญญา
--   หลังไฟล์นี้ ทุกแพ็กเกจ = ล้างแผง+ตรวจสอบระบบ
-- ★ เป็น migration (ไม่ใช่แก้ที่หน้า Package O&M อย่างเดียว) — ก่อน cutover ทีมรันทั้งชุดใหม่บนฐานที่ copy จาก prod
--   seed เดิมจะใส่ข้อความเก่ากลับมา ไฟล์นี้ต้องตามไปตัดอีกรอบ
-- ★ ตัดเฉพาะ 2 วลีนี้ — ขอบเขตงานที่แอดมินแก้เองเป็นอย่างอื่นแล้วไม่โดนแตะ · รันซ้ำได้
-- ★ ใบเสนอราคาที่ออกไปแล้วไม่เปลี่ยน (ข้อความท้ายใบแช่ไว้ในใบ · รายละเอียดใต้แพ็กเกจเก็บเป็นแถวของใบ)

UPDATE dbo.om_packages
   SET scope = NULLIF(REPLACE(REPLACE(scope,
                 N'+ออกใบงานแจ้งผลการดำเนินงาน', N''),
                 N'+ตรวจเช็คตามการแจ้งซ่อมระหว่างสัญญา', N''), N''),
       updated_at = SYSDATETIMEOFFSET()
 WHERE scope LIKE N'%+ออกใบงานแจ้งผลการดำเนินงาน%'
    OR scope LIKE N'%+ตรวจเช็คตามการแจ้งซ่อมระหว่างสัญญา%';
GO
